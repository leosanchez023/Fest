-- MySQL ON UPDATE CURRENT_TIMESTAMP equivalent used only by the tables with
-- update-timestamp columns.
CREATE OR REPLACE FUNCTION public.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  IF TG_ARGV[0] = 'updated_at' THEN
    NEW.updated_at := CURRENT_TIMESTAMP;
  ELSIF TG_ARGV[0] = 'updatedAt' THEN
    NEW."updatedAt" := CURRENT_TIMESTAMP;
  ELSIF TG_ARGV[0] = 'atualizado_em' THEN
    NEW.atualizado_em := CURRENT_TIMESTAMP;
  ELSE
    RAISE EXCEPTION 'Unsupported update timestamp column: %', TG_ARGV[0];
  END IF;
  RETURN NEW;
END;
$$;

