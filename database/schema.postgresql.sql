-- Itens do pedido e produtos que compõem combos.
CREATE TABLE pedido_itens (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id integer NOT NULL,
  produto_id integer DEFAULT NULL,
  tipo_item varchar(10) NOT NULL DEFAULT 'ALUGUEL',
  combo_id integer DEFAULT NULL,
  quantidade integer NOT NULL,
  valor_unitario numeric(10,2) NOT NULL,
  subtotal numeric(10,2) NOT NULL,
  quantidade_entregue integer DEFAULT 0,
  quantidade_devolvida integer DEFAULT 0,
  CONSTRAINT fk_pedido_item_pedido FOREIGN KEY (pedido_id) REFERENCES pedidos(id) ON DELETE CASCADE,
  CONSTRAINT fk_pedido_item_produto FOREIGN KEY (produto_id) REFERENCES produtos(id),
  CONSTRAINT fk_pedido_item_combo FOREIGN KEY (combo_id) REFERENCES combos(id),
  CONSTRAINT chk_pedido_item_origem CHECK (
    (produto_id IS NOT NULL AND combo_id IS NULL)
    OR (produto_id IS NULL AND combo_id IS NOT NULL)
  )
);
CREATE INDEX idx_pedido_itens_pedido ON pedido_itens (pedido_id);
CREATE INDEX idx_pedido_itens_produto ON pedido_itens (produto_id);
-- InnoDB implicitly indexed this foreign key; PostgreSQL does not do so.
CREATE INDEX idx_pedido_itens_combo ON pedido_itens (combo_id);

