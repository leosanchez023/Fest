ALTER TABLE public.endereco
  ADD COLUMN IF NOT EXISTS complemento varchar(150) DEFAULT NULL;

ALTER TABLE public.devolucoes
  ADD COLUMN IF NOT EXISTS valor_restituicao_prevista numeric(10,2) NOT NULL DEFAULT 0.00;

CREATE TABLE IF NOT EXISTS public.creditos_restituicao (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id integer NOT NULL,
  usuario_id integer DEFAULT NULL,
  valor numeric(10,2) NOT NULL,
  descricao text NOT NULL,
  status varchar(9) NOT NULL DEFAULT 'PENDENTE' CONSTRAINT chk_creditos_restituicao_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO')),
  criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  atualizado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_credito_restituicao_pedido FOREIGN KEY (pedido_id) REFERENCES public.pedidos(id) ON DELETE CASCADE,
  CONSTRAINT fk_credito_restituicao_usuario FOREIGN KEY (usuario_id) REFERENCES public.usuario(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_creditos_restituicao_pedido_status
  ON public.creditos_restituicao (pedido_id, status);
CREATE INDEX IF NOT EXISTS idx_creditos_restituicao_usuario
  ON public.creditos_restituicao (usuario_id);

CREATE TABLE IF NOT EXISTS public.restituicoes_pedido (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id integer NOT NULL,
  usuario_id integer DEFAULT NULL,
  valor numeric(10,2) NOT NULL,
  forma_pagamento varchar(17) NOT NULL CONSTRAINT chk_restituicoes_pedido_forma_pagamento CHECK (forma_pagamento IN ('DINHEIRO', 'PIX', 'CARTAO_DEBITO', 'CARTAO_CREDITO', 'TRANSFERENCIA')),
  observacao text DEFAULT NULL,
  status varchar(9) NOT NULL DEFAULT 'PENDENTE' CONSTRAINT chk_restituicoes_pedido_status CHECK (status IN ('PENDENTE', 'PAGO', 'CANCELADO')),
  criado_em timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
  pago_em timestamp without time zone DEFAULT NULL,
  pago_por integer DEFAULT NULL,
  chave_idempotencia varchar(64) DEFAULT NULL,
  CONSTRAINT fk_restituicao_pedido FOREIGN KEY (pedido_id) REFERENCES public.pedidos(id) ON DELETE CASCADE,
  CONSTRAINT fk_restituicao_usuario FOREIGN KEY (usuario_id) REFERENCES public.usuario(id) ON DELETE SET NULL,
  CONSTRAINT fk_restituicao_pago_por FOREIGN KEY (pago_por) REFERENCES public.usuario(id) ON DELETE SET NULL,
  CONSTRAINT uq_restituicoes_chave_idempotencia UNIQUE (chave_idempotencia)
);

CREATE INDEX IF NOT EXISTS idx_restituicoes_pedido_status
  ON public.restituicoes_pedido (pedido_id, status);
CREATE INDEX IF NOT EXISTS idx_restituicoes_usuario
  ON public.restituicoes_pedido (usuario_id);
CREATE INDEX IF NOT EXISTS fk_restituicao_pago_por
  ON public.restituicoes_pedido (pago_por);

ALTER TABLE public.cliente
